CREATE DATABASE IF NOT EXISTS travelsense CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE travelsense;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS trips (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 destination VARCHAR(180) NOT NULL, start_date DATE NULL, end_date DATE NULL,
 member_limit INT NOT NULL DEFAULT 10, budget DECIMAL(12,2) NOT NULL DEFAULT 0,
 currency CHAR(3) NOT NULL DEFAULT 'INR', created_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(created_by) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS trip_members (
 trip_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 role ENUM('owner','admin','member') NOT NULL DEFAULT 'member',
 status ENUM('invited','accepted','left') NOT NULL DEFAULT 'accepted',
 share_location BOOLEAN NOT NULL DEFAULT FALSE, joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(trip_id,user_id), FOREIGN KEY(trip_id) REFERENCES trips(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS live_locations (
 trip_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 latitude DECIMAL(10,7) NOT NULL, longitude DECIMAL(10,7) NOT NULL,
 accuracy DECIMAL(9,2) NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(trip_id,user_id), FOREIGN KEY(trip_id,user_id) REFERENCES trip_members(trip_id,user_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS expenses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, trip_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(160) NOT NULL, amount DECIMAL(12,2) NOT NULL,
 paid_by BIGINT UNSIGNED NOT NULL, owed_by BIGINT UNSIGNED NOT NULL,
 notes TEXT NULL, status ENUM('pending','settled') NOT NULL DEFAULT 'pending',
 created_by BIGINT UNSIGNED NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, settled_at TIMESTAMP NULL,
 FOREIGN KEY(trip_id) REFERENCES trips(id) ON DELETE CASCADE,
 FOREIGN KEY(paid_by) REFERENCES users(id), FOREIGN KEY(owed_by) REFERENCES users(id),
 FOREIGN KEY(created_by) REFERENCES users(id), CHECK(amount>0)
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, trip_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL, type VARCHAR(50) NOT NULL, message VARCHAR(500) NOT NULL,
 read_at TIMESTAMP NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(trip_id) REFERENCES trips(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
